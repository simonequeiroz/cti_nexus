-- =====================================================================
-- Tabelas do CTI Nexus no PostgreSQL (Neon).
-- O Spring roda este arquivo toda vez que liga (spring.sql.init.mode=always).
-- "IF NOT EXISTS": só cria o que ainda não existe; nunca apaga dados.
--
-- Quem grava o quê (igual à aula "Telas do Backend"):
--   usuario                      -> o Java (Spring Boot)
--   todas as outras tabelas      -> o Python (analytics-python/api.py, rota POST /etl)
-- O Java só LÊ as outras tabelas, para o painel (GET /api/clientes e /api/uploads).
-- =====================================================================


-- ===== USUÁRIOS: a única tabela que o Java grava =====
CREATE TABLE IF NOT EXISTS usuario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(120) NOT NULL,
    email               VARCHAR(160) NOT NULL UNIQUE,
    senha_hash          VARCHAR(255) NOT NULL,           -- BCrypt, nunca a senha pura
    cargo               VARCHAR(80),
    papel               VARCHAR(20),                     -- ADMINISTRADOR, ANALISTA, GESTOR (nulo no pedido de acesso)
    situacao            VARCHAR(20)  NOT NULL,           -- PENDENTE, ATIVO, DESATIVADO
    criado_em           TIMESTAMP(6) NOT NULL,
    deve_trocar_senha   BOOLEAN      NOT NULL DEFAULT FALSE, -- senha temporária: troca obrigatória no próximo login
    pediu_nova_senha_em TIMESTAMP(6)                     -- "Esqueci minha senha" esperando o administrador
);


-- ===== CARGAS (cada vez que alguém libera uma planilha para o painel) =====
-- É a trilha de auditoria: quem enviou, quem liberou e quando. (Classe "Telemetria" do plano de ensino.)
CREATE TABLE IF NOT EXISTS upload_lote (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome       VARCHAR(255) NOT NULL,
    total_linhas       INTEGER      NOT NULL,            -- linhas da planilha
    linhas_validas     INTEGER      NOT NULL,            -- gravadas em cliente
    linhas_invalidas   INTEGER      NOT NULL,            -- ficaram de fora (com erro)
    linhas_com_ajuste  INTEGER      NOT NULL DEFAULT 0,  -- tiveram ajuste automático (ex.: IND. -> Indústria)
    enviado_por        BIGINT REFERENCES usuario(id),    -- quem conferiu a planilha
    aprovado_por       BIGINT REFERENCES usuario(id),    -- quem liberou para o painel (permissão aprovar_carga)
    criado_em          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ===== CADASTROS AUXILIARES (cada nome aparece uma vez só) =====
CREATE TABLE IF NOT EXISTS consultor (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS segmento (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE                     -- Indústria, Comércio, Serviços, Saúde, Educação, Tecnologia
);

CREATE TABLE IF NOT EXISTS servico (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE                    -- ex.: MPLS, Firewall, Link Dedicado
);


-- ===== CLIENTES DA CARTEIRA =====
-- Um cliente por código. Se o mesmo código vier numa carga nova, os dados são atualizados (lote_id passa a ser o novo).
CREATE TABLE IF NOT EXISTS cliente (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(60)  NOT NULL UNIQUE,      -- codigo_cliente da planilha
    nome              VARCHAR(255) NOT NULL,
    consultor_id      BIGINT NOT NULL REFERENCES consultor(id),
    segmento_id       BIGINT NOT NULL REFERENCES segmento(id),
    nivel             VARCHAR(1)   NOT NULL,             -- A, B ou C
    faturamento_anual NUMERIC(15,2) NOT NULL,
    data_contratacao  DATE         NOT NULL,
    cidade            VARCHAR(120),
    uf                VARCHAR(2),
    email             VARCHAR(160),
    lote_id           BIGINT NOT NULL REFERENCES upload_lote(id), -- última carga que trouxe este cliente
    atualizado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cliente_lote ON cliente(lote_id);


-- ===== CONTRATOS: quais serviços cada cliente tem (um cliente tem vários serviços) =====
CREATE TABLE IF NOT EXISTS contrato (
    cliente_id BIGINT   NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,
    servico_id BIGINT   NOT NULL REFERENCES servico(id),
    ordem      SMALLINT NOT NULL,                        -- ordem em que o serviço aparecia na planilha
    PRIMARY KEY (cliente_id, servico_id)
);


-- ===== ESTATÍSTICAS DE CADA CARGA (calculadas pelo Python com Pandas) =====
-- Uma linha por segmento e uma linha "Todos" com a carteira inteira.
CREATE TABLE IF NOT EXISTS estatistica_lote (
    lote_id                   BIGINT NOT NULL REFERENCES upload_lote(id) ON DELETE CASCADE,
    segmento                  VARCHAR(80) NOT NULL,
    quantidade                INTEGER NOT NULL,
    faturamento_total         NUMERIC(17,2) NOT NULL,
    faturamento_medio         NUMERIC(15,2) NOT NULL,
    faturamento_mediana       NUMERIC(15,2) NOT NULL,
    faturamento_desvio_padrao NUMERIC(15,2),             -- nulo quando o grupo tem 1 cliente só
    PRIMARY KEY (lote_id, segmento)
);


-- ===== ALTERAÇÕES MANUAIS: quem corrigiu o quê na tela Validação antes de liberar =====
CREATE TABLE IF NOT EXISTS alteracao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id        BIGINT NOT NULL REFERENCES upload_lote(id) ON DELETE CASCADE,
    usuario_id     BIGINT REFERENCES usuario(id),
    linha          INTEGER NOT NULL,                     -- linha da planilha (como no Excel)
    codigo_cliente VARCHAR(60),
    campo          VARCHAR(40) NOT NULL,
    valor_antigo   TEXT,
    valor_novo     TEXT,
    alterado_em    TIMESTAMP WITH TIME ZONE NOT NULL
);
